// Package gen emits Go source code from a parsed FreeRADIUS dictionary.
//
// The generator produces two layers for every modeled attribute type:
//
//   - A typed constant: const AttrUserName = 1
//   - A typed accessor pair: AddUserName(p, "alice") / GetUserName(p)
//
// Types whose runtime codec is not modeled (TypeVSA, TypeExtended) and
// VENDOR sub-attributes (whose wire form requires a VSA wrapper) only
// get the constant — callers must encode them explicitly via packet /
// vendor helpers.
//
// The generator never reads files or runs the toolchain; it takes a
// *parser.Dict and writes to an io.Writer. Callers may use cmd/dict-gen
// for a CLI front-end, or invoke Gen directly from a build script.
package gen

import (
	"fmt"
	"io"
	"sort"
	"strings"

	"github.com/wxccs/radius/dictionary/parser"
)

// Options configures the generator.
type Options struct {
	// Package is the Go package name written into the output header.
	// Defaults to "attrs" when empty.
	Package string
	// Header is written verbatim after the generated-by comment, before
	// the package clause. Useful for adding build tags or doc strings.
	Header string
}

// Gen writes a single Go source file containing constants and accessor
// functions for every attribute / value in p. The output is sorted so
// the same input always produces byte-identical output, making the
// generator suitable for use in deterministic build pipelines.
func Gen(p *parser.Dict, w io.Writer, opt Options) error {
	if p == nil {
		return fmt.Errorf("gen: nil parser.Dict")
	}
	if opt.Package == "" {
		opt.Package = "attrs"
	}

	// Snapshot attribute list and sort by Name for deterministic output.
	attrs := append([]parser.Attr(nil), p.Attributes...)
	sort.SliceStable(attrs, func(i, j int) bool {
		if attrs[i].Vendor != attrs[j].Vendor {
			return attrs[i].Vendor < attrs[j].Vendor
		}
		return attrs[i].Name < attrs[j].Name
	})

	// Snapshot values and sort by (AttributeName, Name).
	values := append([]parser.Val(nil), p.Values...)
	sort.SliceStable(values, func(i, j int) bool {
		if values[i].AttributeName != values[j].AttributeName {
			return values[i].AttributeName < values[j].AttributeName
		}
		return values[i].Name < values[j].Name
	})

	// Detect whether we need net.IP so we can keep the import list
	// minimal (goimports / go vet would otherwise complain about unused
	// imports if the user runs them after generation).
	needsNet := false
	for _, a := range attrs {
		switch a.ValueType {
		case "ipaddr", "ipv6addr":
			needsNet = true
		}
	}

	// Emit header.
	if _, err := fmt.Fprintf(w, "// Code generated by dict-gen. DO NOT EDIT.\n\n"); err != nil {
		return err
	}
	if opt.Header != "" {
		if _, err := fmt.Fprintf(w, "%s\n\n", opt.Header); err != nil {
			return err
		}
	}
	if _, err := fmt.Fprintf(w, "package %s\n\n", opt.Package); err != nil {
		return err
	}

	if err := emitImports(w, needsNet); err != nil {
		return err
	}

	if err := emitAttributeConstants(w, attrs); err != nil {
		return err
	}
	if err := emitValueConstants(w, values); err != nil {
		return err
	}
	if err := emitAccessors(w, attrs); err != nil {
		return err
	}
	return nil
}

// emitImports writes the import block. Only imports actually needed by
// the generated code are included so the output is gofmt-clean.
func emitImports(w io.Writer, needsNet bool) error {
	if !needsNet {
		_, err := fmt.Fprintf(w, "import (\n\t\"github.com/wxccs/radius/packet\"\n)\n\n")
		return err
	}
	_, err := fmt.Fprintf(w, "import (\n\t\"net\"\n\n\t\"github.com/wxccs/radius/packet\"\n)\n\n")
	return err
}

// emitAttributeConstants writes the AttrXxx constant block.
func emitAttributeConstants(w io.Writer, attrs []parser.Attr) error {
	if len(attrs) == 0 {
		return nil
	}
	if _, err := fmt.Fprintf(w, "// Attribute type numbers.\nconst (\n"); err != nil {
		return err
	}
	for _, a := range attrs {
		ident := attrConstName(a)
		if _, err := fmt.Fprintf(w, "\t%s = %d\n", ident, a.Type); err != nil {
			return err
		}
	}
	if _, err := fmt.Fprintf(w, ")\n\n"); err != nil {
		return err
	}
	return nil
}

// emitValueConstants writes the ValXxxYyy enum-value constants, grouped
// by parent attribute name for readability.
func emitValueConstants(w io.Writer, values []parser.Val) error {
	if len(values) == 0 {
		return nil
	}
	if _, err := fmt.Fprintf(w, "// Enumerated values.\nconst (\n"); err != nil {
		return err
	}
	prevAttr := ""
	for _, v := range values {
		if v.AttributeName != prevAttr {
			if prevAttr != "" {
				if _, err := fmt.Fprintln(w); err != nil {
					return err
				}
			}
			if _, err := fmt.Fprintf(w, "\t// %s\n", v.AttributeName); err != nil {
				return err
			}
			prevAttr = v.AttributeName
		}
		ident := valConstName(v.AttributeName, v.Name)
		if _, err := fmt.Fprintf(w, "\t%s = %d\n", ident, v.Number); err != nil {
			return err
		}
	}
	if _, err := fmt.Fprintf(w, ")\n\n"); err != nil {
		return err
	}
	return nil
}

// emitAccessors writes AddXxx / GetXxx pairs for every attribute whose
// runtime codec is modeled. See gen package docs for the type matrix.
func emitAccessors(w io.Writer, attrs []parser.Attr) error {
	for _, a := range attrs {
		sig, ok := accessorSig(a.ValueType)
		if !ok {
			// VSA / extended / vendor sub-attribute: no accessor
			// generated. Leave a doc comment so callers can see why.
			if _, err := fmt.Fprintf(w, "// %s is a %s attribute; no typed accessor is generated.\n// Use packet.NewString / NewOctets or the vendor sub-package instead.\n\n",
				attrConstName(a), a.ValueType); err != nil {
				return err
			}
			continue
		}
		if err := emitOneAccessor(w, a, sig); err != nil {
			return err
		}
	}
	return nil
}

// accessorSignature describes the Go signature emitted for one attribute.
// The bool is false when the value type has no modeled codec and the
// generator should skip the accessor.
type accessorSignature struct {
	goType   string // the Go parameter type
	ctor     string // packet.NewString / NewInteger / NewIPAddr / ...
	needsNet bool   // whether the import requires "net"
	// getBody is the function body (without surrounding braces) that
	// extracts the typed value from a. It must end with a `return` and
	// is wrapped by the generator with the failure path.
	getBody string
}

// accessorSig maps a normalized value-type string to its accessor
// signature. Unknown strings return ok=false.
func accessorSig(vt string) (accessorSignature, bool) {
	switch vt {
	case "string":
		return accessorSignature{
			goType:  "string",
			ctor:    "packet.NewString",
			getBody: "return string(a.Value), true",
		}, true
	case "integer":
		// Use Attribute.Integer() so a malformed Value (not exactly 4
		// bytes) is surfaced as "absent" rather than panicking.
		return accessorSignature{
			goType:  "uint32",
			ctor:    "packet.NewInteger",
			getBody: "n, err := a.Integer()\n\tif err != nil {\n\t\treturn 0, false\n\t}\n\treturn n, true",
		}, true
	case "ipaddr":
		return accessorSignature{
			goType:   "net.IP",
			ctor:     "packet.NewIPAddr",
			needsNet: true,
			getBody:  "ip, err := a.IPAddr()\n\tif err != nil {\n\t\treturn nil, false\n\t}\n\treturn ip, true",
		}, true
	case "ipv6addr":
		return accessorSignature{
			goType:   "net.IP",
			ctor:     "packet.NewIPv6Addr",
			needsNet: true,
			getBody:  "ip, err := a.IPv6Addr()\n\tif err != nil {\n\t\treturn nil, false\n\t}\n\treturn ip, true",
		}, true
	case "octets", "raw":
		// Copy a.Value so callers cannot mutate the packet's internal
		// buffer by writing to the returned slice.
		return accessorSignature{
			goType:  "[]byte",
			ctor:    "packet.NewOctets",
			getBody: "return append([]byte(nil), a.Value...), true",
		}, true
	default:
		// "vsa", "extended": no accessor generated.
		return accessorSignature{}, false
	}
}

// emitOneAccessor writes the Add / Get pair for one attribute.
func emitOneAccessor(w io.Writer, a parser.Attr, sig accessorSignature) error {
	constName := attrConstName(a)
	addName := "Add" + attrIdentBase(a)
	getName := "Get" + attrIdentBase(a)

	if _, err := fmt.Fprintf(w, "// %s appends a %s attribute.\nfunc %s(p *packet.Packet, v %s) {\n\tp.Add(%s(%s, v))\n}\n\n",
		addName, a.Name, addName, sig.goType, sig.ctor, constName); err != nil {
		return err
	}
	if _, err := fmt.Fprintf(w,
		"// %s returns the first %s attribute value, or false if absent.\nfunc %s(p *packet.Packet) (%s, bool) {\n\ta, ok := p.GetOne(%s)\n\tif !ok {\n\t\treturn %s, false\n\t}\n\t%s\n}\n\n",
		getName, a.Name, getName, sig.goType, constName, zeroValue(sig), sig.getBody); err != nil {
		return err
	}
	return nil
}

// zeroValue returns the zero literal for sig.goType, used in the Get
// accessor's failure path.
func zeroValue(sig accessorSignature) string {
	switch sig.goType {
	case "string":
		return `""`
	case "uint32":
		return "0"
	case "net.IP":
		return "nil"
	case "[]byte":
		return "nil"
	default:
		return "nil"
	}
}

// attrConstName returns the canonical constant name for an attribute:
// "Attr" + vendor prefix (if any) + hyphen-stripped CamelCased name.
// We do not attempt to title-case the name segments — FreeRADIUS names
// already use "User-Name" form, so removing hyphens yields "UserName".
// Vendor prefixes use the vendor name verbatim (also hyphen-stripped).
func attrConstName(a parser.Attr) string {
	base := "Attr"
	if a.Vendor != "" {
		base += stripHyphens(a.Vendor) + "_"
	}
	return base + stripHyphens(a.Name)
}

// attrIdentBase returns the identifier portion used in accessor function
// names (no Attr prefix). For vendor sub-attributes it still includes
// the vendor prefix so the accessor name does not collide with standard
// attribute accessors.
func attrIdentBase(a parser.Attr) string {
	if a.Vendor != "" {
		return stripHyphens(a.Vendor) + "_" + stripHyphens(a.Name)
	}
	return stripHyphens(a.Name)
}

// valConstName returns "Val" + AttrName + ValueName with hyphens stripped.
func valConstName(attrName, valName string) string {
	return "Val" + stripHyphens(attrName) + stripHyphens(valName)
}

// stripHyphens removes hyphens (and any spaces) from name and returns the
// concatenated result. "User-Name" → "UserName".
func stripHyphens(name string) string {
	name = strings.ReplaceAll(name, "-", "")
	name = strings.ReplaceAll(name, " ", "")
	return name
}
