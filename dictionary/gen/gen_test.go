// TestGen_FullOutput exercises the complete pipeline with a mixed
// dictionary: string, integer, ipaddr, ipv6addr, octets, raw, vsa
// and extended attributes, plus VENDOR sub-attributes and VALUE
// enumerations. The output must be syntactically valid Go source and
// contain the expected constants and accessor pairs.
func TestGen_FullOutput(t *testing.T) {
	p := &parser.Dict{
		Attributes: []parser.Attr{
			{Name: "User-Name", Type: 1, ValueType: "string"},
			{Name: "NAS-Port", Type: 5, ValueType: "integer"},
			{Name: "NAS-IP-Address", Type: 4, ValueType: "ipaddr"},
			{Name: "NAS-IPv6-Address", Type: 95, ValueType: "ipv6addr"},
			{Name: "State", Type: 24, ValueType: "octets"},
			{Name: "TLS-Session-Info", Type: 145, ValueType: "raw"},
			{Name: "Vendor-Specific", Type: 26, ValueType: "vsa"},
			{Name: "Extended-Type-1", Type: 241, ValueType: "extended"},
			{Name: "MS-CHAP-Response", Type: 1, ValueType: "octets", Vendor: "Microsoft"},
		},
		Values: []parser.Val{
			{AttributeName: "Service-Type", Name: "Login-User", Number: 1},
			{AttributeName: "Service-Type", Name: "Framed-User", Number: 2},
		},
		Vendors: []parser.Vendor{
			{Name: "Microsoft", ID: 311},
		},
	}

	var buf bytes.Buffer
	require.NoError(t, Gen(p, &buf, Options{Package: "attrs"}))
	out := buf.String()

	// 1) The output must be valid Go source.
	fset := token.NewFileSet()
	_, err := goparser.ParseFile(fset, "attrs.go", out, goparser.AllErrors)
	require.NoErrorf(t, err, "generated output is not valid Go source:\n%s", out)

	// 2) Attribute constants present for every attribute.
	for _, want := range []string{
		"AttrUserName = 1",
		"AttrNASPort = 5",
		"AttrNASIPAddress = 4",
		"AttrNASIPv6Address = 95",
		"AttrState = 24",
		"AttrTLSSessionInfo = 145",
		"AttrVendorSpecific = 26",
		"AttrExtendedType1 = 241",
		"AttrMicrosoft_MSCHAPResponse = 1",
	} {
		assert.Contains(t, out, want, "expected constant %q in output", want)
	}

	// 3) Value constants present, with the attribute name used as a
	// comment separator between groups.
	assert.Contains(t, out, "// Service-Type")
	assert.Contains(t, out, "ValServiceTypeLoginUser = 1")
	assert.Contains(t, out, "ValServiceTypeFramedUser = 2")

	// 4) Accessor pairs present for modeled types.
	for _, want := range []string{
		"func AddUserName(p *packet.Packet, v string) {",
		"func GetUserName(p *packet.Packet) (string, bool) {",
		"func AddNASPort(p *packet.Packet, v uint32) {",
		"func GetNASPort(p *packet.Packet) (uint32, bool) {",
		"func AddNASIPAddress(p *packet.Packet, v net.IP) {",
		"func GetNASIPAddress(p *packet.Packet) (net.IP, bool) {",
		"func AddNASIPv6Address(p *packet.Packet, v net.IP) {",
		"func AddState(p *packet.Packet, v []byte) {",
		"func GetState(p *packet.Packet) ([]byte, bool) {",
		"func AddTLSSessionInfo(p *packet.Packet, v []byte) {",
	} {
		assert.Contains(t, out, want, "expected accessor %q in output", want)
	}

	// 5) No accessor for vsa / extended — only a doc comment.
	assert.NotContains(t, out, "func AddVendorSpecific(",
		"vsa attributes must not get a typed accessor")
	assert.NotContains(t, out, "func AddExtendedType1(",
		"extended attributes must not get a typed accessor")

	// 6) No accessor for vendor sub-attributes either.
	assert.NotContains(t, out, "func AddMicrosoft_MSChapResponse(",
		"vendor sub-attributes must not get a typed accessor")

	// 7) The "net" import is required because we have ipaddr / ipv6addr.
	assert.Contains(t, out, "\"net\"")

	// 8) The header banner is present.
	assert.Contains(t, out, "// Code generated by dict-gen. DO NOT EDIT.")
	assert.Contains(t, out, "package attrs")
}

func TestGen_MinimalImportsWhenNoIP(t *testing.T) {
	// When the dictionary has no ipaddr / ipv6addr attribute, the
	// generated file must not import "net" — otherwise go vet would
	// complain about an unused import.
	p := &parser.Dict{Attributes: []parser.Attr{
		{Name: "User-Name", Type: 1, ValueType: "string"},
		{Name: "NAS-Port", Type: 5, ValueType: "integer"},
	}}
	var buf bytes.Buffer
	require.NoError(t, Gen(p, &buf, Options{Package: "attrs"}))
	assert.NotContains(t, buf.String(), "\"net\"",
		"net import must be omitted when no IP-typed attribute exists")
}

func TestGen_Deterministic(t *testing.T) {
	// Same input → byte-identical output. Important for CI checks.
	p := &parser.Dict{Attributes: []parser.Attr{
		{Name: "Zebra", Type: 100, ValueType: "string"},
		{Name: "Apple", Type: 101, ValueType: "integer"},
		{Name: "Mango", Type: 102, ValueType: "octets"},
	}}
	var b1, b2 bytes.Buffer
	require.NoError(t, Gen(p, &b1, Options{Package: "attrs"}))
	require.NoError(t, Gen(p, &b2, Options{Package: "attrs"}))
	assert.Equal(t, b1.String(), b2.String())

	// And the output is sorted alphabetically by attribute name,
	// regardless of input order.
	out := b1.String()
	assert.Less(t, strings.Index(out, "AttrApple"), strings.Index(out, "AttrMango"))
	assert.Less(t, strings.Index(out, "AttrMango"), strings.Index(out, "AttrZebra"))
}

func TestGen_SortsValuesByAttributeThenName(t *testing.T) {
	p := &parser.Dict{Values: []parser.Val{
		{AttributeName: "Framed-Protocol", Name: "PPP", Number: 1},
		{AttributeName: "Service-Type", Name: "Login-User", Number: 1},
		{AttributeName: "Service-Type", Name: "Framed-User", Number: 2},
	}}
	var buf bytes.Buffer
	require.NoError(t, Gen(p, &buf, Options{Package: "attrs"}))
	out := buf.String()

	// Framed-Protocol group comes before Service-Type (alphabetical: F < S).
	assert.Less(t, strings.Index(out, "// Framed-Protocol"), strings.Index(out, "// Service-Type"))
	// Within Service-Type: FramedUser < LoginUser (alphabetical).
	assert.Less(t, strings.Index(out, "ValServiceTypeFramedUser"), strings.Index(out, "ValServiceTypeLoginUser"))
}

func TestGen_HeaderOption(t *testing.T) {
	p := &parser.Dict{Attributes: []parser.Attr{{Name: "Foo", Type: 1, ValueType: "string"}}}
	var buf bytes.Buffer
	require.NoError(t, Gen(p, &buf, Options{
		Package: "attrs",
		Header:  "//go:build siteattrs",
	}))
	out := buf.String()
	assert.Contains(t, out, "//go:build siteattrs")
	// Header is placed before the package clause.
	assert.Less(t, strings.Index(out, "//go:build siteattrs"), strings.Index(out, "package attrs"))
}

func TestGen_NilDict(t *testing.T) {
	var buf bytes.Buffer
	err := Gen(nil, &buf, Options{Package: "attrs"})
	require.Error(t, err)
	assert.Contains(t, err.Error(), "nil")
}

func TestGen_EmptyDict(t *testing.T) {
	// An empty Dict must still produce valid Go with the package clause.
	var buf bytes.Buffer
	require.NoError(t, Gen(&parser.Dict{}, &buf, Options{Package: "attrs"}))
	out := buf.String()
	assert.Contains(t, out, "package attrs")

	// And still valid Go.
	fset := token.NewFileSet()
	_, err := goparser.ParseFile(fset, "attrs.go", out, goparser.AllErrors)
	require.NoError(t, err)
}

func TestGen_DefaultPackageName(t *testing.T) {
	p := &parser.Dict{Attributes: []parser.Attr{{Name: "Foo", Type: 1, ValueType: "string"}}}
	var buf bytes.Buffer
	require.NoError(t, Gen(p, &buf, Options{}))
	assert.Contains(t, buf.String(), "package attrs")
}
